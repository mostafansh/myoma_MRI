"""Render the studio's docker-compose.yml and Caddyfile from readers.json.

Standard library only. YAML is written by hand from string templates.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

STUDIO_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(STUDIO_DIR / "portal"))

import portal_core  # noqa: E402
from portal_core import RESERVED_IDS  # noqa: E402

READER_ID_RE = portal_core.READER_ID_RE
_DRIVE_RE = re.compile(r"^[A-Za-z]:[\/]")


def _check_ids(reader_ids: list[str]) -> None:
    for rid in reader_ids:
        if not isinstance(rid, str) or not READER_ID_RE.match(rid):
            raise ValueError(f"Invalid reader id: {rid!r}")
        if rid in RESERVED_IDS:
            raise ValueError(f"Reserved reader id: {rid!r}")


def _q(text: str) -> str:
    """Quote a YAML scalar (JSON strings are valid YAML double-quoted scalars)."""
    return json.dumps(text.replace("\\", "/"), ensure_ascii=False)


def render_compose(reader_ids: list[str], dataset_root: str, readers_root: str, portal_data_dir: str) -> str:
    _check_ids(reader_ids)
    lines = [
        "# Generated by studio/studio_config.py. Do not edit.",
        "services:",
        "  caddy:",
        "    image: caddy:2.8",
        "    restart: unless-stopped",
        "    ports:",
        '      - "443:443"',
        "    volumes:",
        "      - ./Caddyfile:/etc/caddy/Caddyfile:ro",
        "      - caddy-data:/data",
        "    networks:",
        "      - edge",
    ]
    lines += [f"      - net-{rid}" for rid in reader_ids]
    lines += [
        "  portal:",
        "    image: myoma-studio-portal",
        "    restart: unless-stopped",
        "    volumes:",
        f"      - {_q(portal_data_dir + ':/portal')}",
        f"      - {_q(dataset_root + ':/data:ro')}",
        f"      - {_q(readers_root + ':/readers:ro')}",
        "    networks:",
        "      - edge",
    ]
    for rid in reader_ids:
        lines += [
            f"  slicer-{rid}:",
            "    image: myoma-studio-slicer",
            "    restart: unless-stopped",
            "    environment:",
            '      MYOMA_REVIEW_LITE_STUDIO: "1"',
            "    volumes:",
            f"      - {_q(dataset_root + ':/data:ro')}",
            f"      - {_q(readers_root + '/' + rid + ':/review')}",
            f"      - settings-{rid}:/home/reader/.config",
            "    networks:",
            f"      - net-{rid}",
        ]
    lines += ["networks:", "  edge: {}"]
    for rid in reader_ids:
        lines += [f"  net-{rid}:", "    internal: true"]
    lines += ["volumes:", "  caddy-data: {}"]
    lines += [f"  settings-{rid}: {{}}" for rid in reader_ids]
    return "\n".join(lines) + "\n"


def render_caddyfile(reader_ids: list[str], server_address: str) -> str:
    _check_ids(reader_ids)
    if not re.match(r"^[A-Za-z0-9.:\-\[\]]+$", server_address or ""):
        raise ValueError(f"Invalid server address: {server_address!r}")
    lines = [f"{server_address} {{", "    tls internal", ""]
    for rid in reader_ids:
        lines += [
            f"    handle /{rid}/* {{",
            "        route {",
            "            forward_auth portal:9000 {",
            "                uri /auth",
            "            }",
            f"            uri strip_prefix /{rid}",
            f"            reverse_proxy slicer-{rid}:6080",
            "        }",
            "    }",
            "",
        ]
    lines += [
        "    handle /login* {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle /logout {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle /admin* {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle /unavailable {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle / {",
        "        redir * /login",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def read_dataset_root(config_path: Path) -> str:
    """Return the configured dataset root as a forward-slash string (need not exist)."""
    config_path = Path(config_path)
    try:
        data = json.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ValueError(f"Cannot read {config_path}: {exc}") from exc
    value = data.get("dataset_root") if isinstance(data, dict) else None
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{config_path} has no dataset_root")
    value = value.strip().replace("\\", "/")
    if value.startswith("/") or _DRIVE_RE.match(value):
        return value
    return (config_path.resolve().parent / value).as_posix()


def _abs_posix(path: str) -> str:
    return Path(path).resolve().as_posix()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    render = sub.add_parser("render", help="write docker-compose.yml and Caddyfile")
    render.add_argument("--server-address", required=True)
    render.add_argument("--review-config", default="review-config.json")
    render.add_argument("--portal-data", default="studio/portal-data")
    render.add_argument("--readers-root", default="studio/readers")
    render.add_argument("--out", default="studio/generated")
    args = parser.parse_args(argv)

    try:
        readers = portal_core.load_readers(Path(args.portal_data) / "readers.json")
        ids = [r.id for r in readers.values() if not r.admin]
        dataset_root = read_dataset_root(Path(args.review_config))
        compose = render_compose(ids, dataset_root, _abs_posix(args.readers_root), _abs_posix(args.portal_data))
        caddy = render_caddyfile(ids, args.server_address)
    except (portal_core.PortalError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "docker-compose.yml").write_text(compose, encoding="utf-8", newline="\n")
    (out / "Caddyfile").write_text(caddy, encoding="utf-8", newline="\n")
    print(f"Wrote {out / 'docker-compose.yml'} and {out / 'Caddyfile'} ({len(ids)} reader container(s)).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
