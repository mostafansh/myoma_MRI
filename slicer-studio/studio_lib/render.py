"""Render the studio's docker-compose.yml and Caddyfile from a deployment.

Standard library only. YAML is written by hand from string templates.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path

import portal_core
from portal_core import RESERVED_IDS, USER_ID_RE

from .deployment import Deployment, check_address, missing_workspace_files, project_name
from .manifest import expand_env


def _check_ids(user_ids: list[str]) -> None:
    for uid in user_ids:
        if not isinstance(uid, str) or not USER_ID_RE.match(uid):
            raise ValueError(f"Invalid user id: {uid!r}")
        if uid in RESERVED_IDS:
            raise ValueError(f"Reserved user id: {uid!r}")


def _value(text: str) -> str:
    """Quote a compose value verbatim: compose interpolates '$', so it is doubled."""
    return json.dumps(text.replace("$", "$$"), ensure_ascii=False)


def _q(text: str) -> str:
    """Quote a host-path-bearing compose scalar: forward slashes, '$' doubled, JSON double quotes."""
    return _value(text.replace("\\", "/"))


def _host(path: Path) -> str:
    return Path(path).resolve().as_posix()


def render_compose(deployment: Deployment, user_ids: list[str]) -> str:
    _check_ids(user_ids)
    check_address(deployment.server_address)
    manifest = deployment.manifest
    users_dir = _host(deployment.users_dir)
    dataset = _host(deployment.dataset) if manifest.uses_dataset and deployment.dataset else None
    if manifest.uses_dataset and dataset is None:
        raise ValueError("The module uses a dataset but the deployment has none")
    lines = [
        "# Generated by slicer-studio. Do not edit.",
        f"name: {project_name(Path(deployment.root).resolve())}",
        "services:",
        "  caddy:",
        "    image: caddy:2.8",
        "    restart: unless-stopped",
        "    ports:",
        f'      - "{deployment.server_address}:443:443"',
        "    volumes:",
        "      - ./Caddyfile:/etc/caddy/Caddyfile:ro",
        "      - caddy-data:/data",
        "    networks:",
        "      - edge",
    ]
    lines += [f"      - net-{uid}" for uid in user_ids]
    portal_command = "--users-root /workspaces" + (" --data-root /data" if dataset else "")
    lines += [
        "  portal:",
        "    image: slicer-studio-portal",
        "    restart: unless-stopped",
        f"    command: {_value(portal_command)}",
        "    environment:",
        f"      STUDIO_TITLE: {_value(manifest.title)}",
        "    volumes:",
        f"      - {_q(_host(deployment.portal_dir) + ':/portal')}",
        f"      - {_q(users_dir + ':/workspaces:ro')}",
    ]
    if dataset:
        lines.append(f"      - {_q(dataset + ':/data:ro')}")
    lines += ["    networks:", "      - edge"]

    module_paths = ",".join(f"/modules/{n}" for n in range(len(manifest.module_dirs)))
    env = {
        "SLICER_STUDIO": "1",
        "STUDIO_START_MODULE": manifest.start_module,
        "STUDIO_MODULE_PATHS": module_paths,
        **expand_env(manifest),
    }
    for uid in user_ids:
        lines += [
            f"  slicer-{uid}:",
            "    image: slicer-studio-slicer",
            "    restart: unless-stopped",
            "    init: true",
            "    environment:",
        ]
        lines += [f"      {key}: {_value(value)}" for key, value in env.items()]
        lines.append("    volumes:")
        lines += [f"      - {_q(_host(d) + ':/modules/' + str(n) + ':ro')}"
                  for n, d in enumerate(manifest.module_dirs)]
        lines.append(f"      - {_q(users_dir + '/' + uid + ':/workspace')}")
        if dataset:
            lines.append(f"      - {_q(dataset + ':/data:ro')}")
        lines += [
            f"      - settings-{uid}:/home/user/.config",
            "    networks:",
            f"      - net-{uid}",
        ]
    lines += ["networks:", "  edge: {}"]
    for uid in user_ids:
        lines += [f"  net-{uid}:", "    internal: true"]
    lines += ["volumes:", "  caddy-data: {}"]
    lines += [f"  settings-{uid}: {{}}" for uid in user_ids]
    return "\n".join(lines) + "\n"


def render_caddyfile(user_ids: list[str], server_address: str) -> str:
    _check_ids(user_ids)
    check_address(server_address)
    # Browsers send no SNI for an IP address, and Caddy then matches on the
    # container's own address, so without default_sni the TLS handshake fails.
    lines = ["{", f"    default_sni {server_address}", "}", "", f"{server_address} {{", "    tls internal", ""]
    for uid in user_ids:
        lines += [
            f"    handle /{uid}/* {{",
            "        route {",
            "            forward_auth portal:9000 {",
            "                uri /auth",
            "            }",
            f"            uri strip_prefix /{uid}",
            f"            reverse_proxy slicer-{uid}:6080",
            "        }",
            "    }",
            "",
        ]
    lines += [
        "    handle /login* {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle /logout {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle /admin* {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle /unavailable {",
        "        reverse_proxy portal:9000",
        "    }",
        "    handle / {",
        "        redir * /login",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


@dataclass
class RenderResult:
    user_ids: list[str]
    warnings: list[str]


def _write_atomic(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


def render(deployment: Deployment) -> RenderResult:
    """Render both files for the deployment's non-admin users. Writes nothing if validation fails."""
    users = portal_core.load_users(deployment.portal_dir / "users.json")
    user_ids = sorted(u.id for u in users.values() if not u.admin)
    compose = render_compose(deployment, user_ids)
    caddy = render_caddyfile(user_ids, deployment.server_address)
    warnings = []
    for uid in user_ids:
        if not (deployment.users_dir / uid).is_dir():
            warnings.append(f"user {uid}: workspace folder {deployment.users_dir / uid} does not exist")
            continue
        missing = missing_workspace_files(deployment, uid)
        if missing:
            warnings.append(f"user {uid}: workspace is missing {', '.join(missing)}")
    deployment.generated_dir.mkdir(parents=True, exist_ok=True)
    _write_atomic(deployment.generated_dir / "docker-compose.yml", compose)
    _write_atomic(deployment.generated_dir / "Caddyfile", caddy)
    return RenderResult(user_ids, warnings)
